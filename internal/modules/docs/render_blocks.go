import "strings"

// drawLowerBlocks renders the side-by-side detail boxes beneath the body. For
// payslips it shows the employee Bank Details (when present) + Notes & Terms; the
// report body uses neither. Boxes are only drawn when they have content. Returns the
// y below the taller box (or unchanged when nothing is rendered).
func (p *painter) drawLowerBlocks(d *Document, lY float64) float64 {
	bw := (contentW - 6.0) / 2
	bx2 := leftX + bw + 6.0
	lowH := 30.0

	hasBank := d.BankDetails != nil && !d.BankDetails.IsEmpty()
	hasNotes := d.Notes != "" || d.Terms != ""
	if !hasBank && !hasNotes {
		return lY
	}

	if hasBank {
		x := leftX
		if !hasNotes {
			x = leftX
		}
		p.box(x, lY, bw, lowH)
		p.text(x+3, lY+3.0, "PAID TO ACCOUNT", "B", 8, p.pal.blue)
		p.bankRows(x+3, lY+7.5, d.BankDetails)
	}
	if hasNotes {
		x := bx2
		if !hasBank {
			x = leftX
		}
		p.box(x, lY, bw, lowH)
		p.text(x+3, lY+3.0, "NOTES & TERMS", "B", 8, p.pal.blue)
		y := lY + 7.5
		for _, n := range notesLines(d) {
			y = p.multiCell(x+3, y, bw-6, 3.8, "•  "+n, "", 8.6, p.pal.grey) + 1.0
		}
	}
	return lY + lowH
}

// drawSignatures renders the Prepared By / Approved By signature lines.
func (p *painter) drawSignatures(d *Document, sY float64) float64 {
	sigW := 80.0
	leftRole, rightRole := "Prepared By", "Approved By"
	p.drawSig(leftX, sY, sigW, leftRole, d.PreparedBy)
	p.drawSig(rightX-sigW, sY, sigW, rightRole, d.ApprovedBy)
	return sY
}

func (p *painter) drawSig(x, sY, sigW float64, role, name string) {
	p.setDraw(p.pal.navy)
	p.pdf.SetLineWidth(0.5)
	p.pdf.Line(x, sY, x+sigW, sY)
	label := role + " — "
	p.pdf.SetFont("Helvetica", "", 9)
	p.setText(p.pal.grey)
	p.pdf.SetXY(x, sY+1.5)
	p.pdf.CellFormat(0, 4, p.tr(label), "", 0, "L", false, 0, "")
	if name != "" {
		w := p.pdf.GetStringWidth(p.tr(label))
		p.pdf.SetFont("Helvetica", "B", 9.6)
		p.setText(p.pal.navy)
		p.pdf.SetXY(x+w, sY+1.5)
		p.pdf.CellFormat(0, 4, p.tr(name), "", 0, "L", false, 0, "")
	}
}

// drawFooter renders the closing disclaimer line(s).
func (p *painter) drawFooter(d *Document, fY float64) {
	p.setDraw(p.pal.line)
	p.pdf.SetLineWidth(0.2)
	p.pdf.Line(leftX, fY, rightX, fY)

	p.pdf.SetFont("Helvetica", "", 8.3)
	p.setText(p.pal.muted)
	p.pdf.SetXY(leftX, fY+2.0)
	name := ifEmpty(d.TenantName, "the issuer")
	p.pdf.CellFormat(contentW, 4, p.tr(footerLead(d.Type, name)), "", 1, "C", false, 0, "")
	if meta := footerMeta(d); meta != "" {
		p.pdf.SetX(leftX)
		p.pdf.CellFormat(contentW, 4, p.tr(meta), "", 1, "C", false, 0, "")
	}
}

// ── small block helpers ───────────────────────────────────────────────────────

// kvIf prints a key/value pair only when v is non-empty, advancing y by 4mm.
func (p *painter) kvIf(x, y float64, k, v string) float64 {
	if v == "" {
		return y
	}
	p.kv(x, y, k, v)
	return y + 4.0
}

func (p *painter) bankRows(x, y float64, bd *BankDetails) {
	y = p.kvIf(x, y, "Bank", bd.BankName)
	y = p.kvIf(x, y, "Branch / IBAN", bd.BranchCode)
	y = p.kvIf(x, y, "Account Name", bd.AccountName)
	_ = p.kvIf(x, y, "Account No", bd.AccountNumber)
}

func footerLead(t DocType, name string) string {
	switch t {
	case DocTypePayrollReport:
		return "This report is generated by " + name + " and is strictly confidential."
	default:
		return "This payslip is issued by " + name + " and is strictly confidential."
	}
}

func footerMeta(d *Document) string {
	parts := []string{}
	if addr := strings.Join(companyAddressLines(d), ", "); addr != "" {
		parts = append(parts, addr)
	}
	if d.TaxPIN != "" {
		parts = append(parts, "Tax PIN: "+d.TaxPIN)
	}
	if d.Tagline != "" {
		parts = append(parts, d.Tagline)
	}
	return strings.Join(parts, "  |  ")
}
